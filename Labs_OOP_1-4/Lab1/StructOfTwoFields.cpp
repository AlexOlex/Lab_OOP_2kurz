void StructOfTwoFields::Init(double a, double b)
{
    //перевірка чи a від'ємна і b неціле (fmod повертає дробову частину числа b)
    if (a < 0.0 && std::fmod(b, 1.0) != 0.0) 
    { 
        std::cerr << " Від'ємне число " << a << " не можна підносити до нецілого степеня" << b
                  << " Будуть втановлені нульові значення по замовчуванню для обох чисел"
                  << std::endl;
        first = 0.0;
        second = 0.0;
    }
    else 
    {
        first = a;
        second = b;
    }
}

